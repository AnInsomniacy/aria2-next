#!/usr/bin/env python3
"""Writes docs/options.md from `aria2-next --help`, so the reference always
matches the option catalogue.

usage: make_options_doc.py /path/to/aria2-next > docs/options.md
"""

import re
import subprocess
import sys

TAGS = [
    ("basic", "Basic"),
    ("http", "HTTP, HTTPS and SFTP"),
    ("file", "Files"),
    ("bittorrent", "BitTorrent"),
    ("metalink", "Metalink"),
    ("ed2k", "ED2K"),
    ("media", "HLS and DASH"),
    ("rpc", "RPC"),
    ("advanced", "Advanced"),
]
HEAD = re.compile(r"^\s+(?:-(\S), )?--([^\s=]+)(?:=(\S+))?$")


def options(engine: str, tag: str) -> list[dict[str, str]]:
    text = subprocess.run([engine, f"--help=#{tag}"], capture_output=True, text=True,
                          encoding="utf-8", check=True).stdout
    found: list[dict[str, str]] = []
    for line in text.splitlines():
        match = HEAD.match(line)
        if match:
            short, name, argument = match.groups()
            found.append({"short": short or "", "name": name, "argument": argument or "",
                          "help": "", "default": ""})
        elif found and line.startswith("        Default: "):
            found[-1]["default"] = line.removeprefix("        Default: ")
        elif found and line.startswith("        "):
            found[-1]["help"] += (" " if found[-1]["help"] else "") + line.strip()
    return found


def cell(text: str) -> str:
    return text.replace("|", "\\|")


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__.strip(), file=sys.stderr)
        return 2
    out = [
        "# Options",
        "",
        "Generated by `docs/make_options_doc.py` from `aria2-next --help`; do not edit.",
        "",
        "Every option can be given on the command line (`--name=value`), in the",
        "configuration file (`name=value`), in a session file under a URI, and",
        "through RPC (`aria2.addUri` options, `aria2.changeOption`,",
        "`aria2.changeGlobalOption`). `aria2-next --help=#TAG` prints one section,",
        "`aria2-next --help=WORD` the options whose names contain WORD.",
        "",
    ]
    for tag, title in TAGS:
        found = options(sys.argv[1], tag)
        if not found:
            continue
        out += [f"## {title}", "", "| Option | Value | Default | Description |",
                "| --- | --- | --- | --- |"]
        for option in found:
            name = f"`--{option['name']}`"
            if option["short"]:
                name = f"`-{option['short']}`, " + name
            argument = option["argument"]
            value = " \\| ".join(f"`{v}`" for v in argument.split("|")) if "|" in argument \
                else argument.upper() if argument else "flag"
            default = f"`{option['default']}`" if option["default"] else ""
            out.append(f"| {name} | {value} | {cell(default)} | {cell(option['help'])} |")
        out.append("")
    sys.stdout.write("\n".join(out))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
